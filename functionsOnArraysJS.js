let table = [1 , 2 , 3 , 4 , 5];
//push permet d'ajouter un element à la fin du tableau
table.push(6);
console.log(table);

//shift and unshift 
// elle permet de supprimer le premier elem
table.shift();
console.log(table);


//unshift pour ajouter un element au premier du tableau

table.unshift(0);
console.log(table);

//pop supprime le dernier elem
table.pop();
console.log(table);



